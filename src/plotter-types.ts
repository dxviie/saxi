/**
 * Types shared between the server (plotter connections and plotting) and the UI (plotter switcher, settings and
 * overview). Keep this file free of node/browser-specific imports.
 */

import type { Hardware } from "./ebb.js";
import type { PlanHardware, PlanOptions } from "./planning.js";
import type { Vec2 } from "./vec.js";

/**
 * How saxi talks to a plotter:
 * - `ebb`: the EiBotBoard of an AxiDraw, NextDraw or similar, which saxi drives step by step.
 * - `hpgl`: an HP-GL plotter on a serial port, such as the HP 7475A, which plans its own motion.
 */
export type PlotterKind = "ebb" | "hpgl";

export const PLOTTER_KINDS: PlotterKind[] = ["ebb", "hpgl"];

/** A `port` that connects to a simulated plotter instead of a real one, to try saxi out. */
export const SIMULATED_PORT = "simulated";

/** Plan options that belong to the machine rather than to a drawing: calibrated once per plotter. */
export const MACHINE_SETTING_KEYS = [
  "penUpHeight",
  "penDownHeight",
  "penDownAcceleration",
  "penDownMaxVelocity",
  "penDownCorneringFactor",
  "penUpAcceleration",
  "penUpMaxVelocity",
  "penDropDuration",
  "penLiftDuration",
  "penHome",
] as const;

export type MachineSettingKey = (typeof MACHINE_SETTING_KEYS)[number];

/** Per-plotter calibration. Missing values fall back to the plan defaults. */
export type PlotterSettings = Partial<Pick<PlanOptions, MachineSettingKey>> & {
  /** HP-GL: the carousel pen (1-6) to plot with. */
  pen?: number;
};

export interface PlotterConfig {
  /** Stable identifier, generated by the server ("default" for the plotter saxi starts with). */
  id: string;
  /** Display name. */
  name: string;
  kind: PlotterKind;
  /**
   * Serial port path, e.g. `/dev/serial/by-id/usb-FTDI_…`, `COM3`, or `simulated`. Empty connects to the first
   * AxiDraw found that no other plotter uses (EBB only).
   */
  port: string;
  /**
   * EBB only, with an empty `port`: only connect to the board with this USB serial number. EBB firmware 2.5.5 and
   * newer reports its nickname (set with the ST command) as the serial number.
   */
  serialNumber: string;
  /** EBB only: the machine model, which sets the servo range and output pin. */
  hardware: Hardware;
  /** HP-GL only: the baud rate set with the plotter's rear switches. */
  baudRate: number;
  /**
   * HP-GL only: the cable connects the plotter's buffer-full line (DTR, pin 20) to the adapter's CTS, so the
   * serial port can stop sending by itself. Without it saxi paces the data in software, which works over any
   * null-modem cable.
   */
  rtscts: boolean;
  /** Disabled plotters are not connected to. */
  enabled: boolean;
  settings: PlotterSettings;
}

/** What a plot is, for the overview and the timelapse library. */
export interface PlotJobInfo {
  /** Usually the file name of the drawing. */
  name: string;
  /** Paper the drawing was laid out on, in mm. */
  paperSize?: Vec2;
  /** What the plan was made for. Plans must match the plotter's units. */
  hardware?: PlanHardware;
  /** HP-GL: carousel pen (1-6). */
  pen?: number;
  /** HP-GL: pen-down speed in mm/s. */
  penSpeed?: number;
}

export interface PlotJobStatus extends PlotJobInfo {
  startedAt: string;
  /** Estimated duration of the whole plot, in seconds. */
  estimatedSeconds: number;
}

/** Paper the plotter is set up for, as an HP-GL plotter reports it. */
export interface PlotterPaper {
  /** e.g. `A4`, `A3`, `A` (US letter) or `B` (US tabloid). */
  name: string;
  /** Size of that paper, landscape, in mm. */
  size: Vec2;
}

export interface PlotterStatus {
  connected: boolean;
  /** Serial port in use. */
  path: string | null;
  /** What answered, e.g. `EBB 2.8.1` or `HP 7475A`. */
  model: string | null;
  /** HP-GL: paper size selected on the plotter. */
  paper: PlotterPaper | null;
  /** Something for a person to fix: paper lever raised, VIEW pressed, connection error… */
  attention: string | null;
  /** Last connection problem. */
  error: string | null;
  plotting: boolean;
  paused: boolean;
  job: PlotJobStatus | null;
  /** Index of the motion the plotter is at, and the number of motions in the plan. */
  progress: { motionIdx: number; motions: number } | null;
}

export type PlotterWithStatus = PlotterConfig & { status: PlotterStatus };

/** A serial port on the server, offered in the plotter form. */
export interface SerialPortListing {
  /** Path to store as the plotter's `port`: a stable /dev/serial link where there is one. */
  path: string;
  /** Every path that refers to this port. */
  paths: string[];
  manufacturer: string | null;
  serialNumber: string | null;
  vendorId: string | null;
  productId: string | null;
  /** An EiBotBoard (AxiDraw and friends). */
  ebb: boolean;
  /** Plotters configured with this port. */
  usedBy: Array<{ id: string; name: string }>;
}

export interface ProbeResult {
  /** Baud rate the plotter answered at, or null if nothing answered. */
  baudRate: number | null;
  /** What it identified as, e.g. `7475A`. */
  model: string | null;
  paper: PlotterPaper | null;
  /** The baud rates tried, in order. */
  tried: number[];
}

export const defaultPlotterConfig: Omit<PlotterConfig, "id"> = {
  name: "",
  kind: "ebb",
  port: "",
  serialNumber: "",
  hardware: "v3",
  baudRate: 9600,
  rtscts: false,
  enabled: true,
  settings: {},
};

/** Settings a new HP-GL plotter starts with: 10 cm/s suits technical pens. */
export const defaultHpglSettings: PlotterSettings = { penDownMaxVelocity: 100, pen: 1 };

/** What saxi plans for on a plotter. */
export function planHardwareFor(plotter: Pick<PlotterConfig, "kind" | "hardware">): PlanHardware {
  return plotter.kind === "hpgl" ? "hp7475a" : plotter.hardware;
}
